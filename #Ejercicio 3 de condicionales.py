##Dias de la semana

dia=input("Ingresar dia de la semana: ").lower()
if dia=="lunes":
    print("Lunes otra vez...")
elif dia=="viernes":
    print("Ya es viernes!!")
elif dia=="sábado" or dia=="sabado" or dia=="domingo":
    print("Fin de semana, casi lunes!!")
else:
    print("Dia para aprovechar las ofertas de steam")
